enum ArcQuestPrerequisitePolicy { all, any, unverified }

enum ArcQuestDependencyConfidence { confirmed, strong, provisional }

class ArcQuestCatalogueNode {
  const ArcQuestCatalogueNode({
    required this.id,
    required this.displayName,
    required this.trader,
    required this.canonicalOrder,
    required this.mapNames,
    required this.contentUpdate,
    required this.prerequisiteQuestIds,
    required this.prerequisitePolicy,
    required this.dependencyConfidence,
    this.catalogueVersion = ArcQuestCatalogue.version,
  });

  final String id;
  final String displayName;
  final String trader;
  final int canonicalOrder;
  final List<String> mapNames;
  final String contentUpdate;
  final List<String> prerequisiteQuestIds;
  final ArcQuestPrerequisitePolicy prerequisitePolicy;
  final ArcQuestDependencyConfidence dependencyConfidence;
  final String catalogueVersion;

  bool get isRoot => prerequisiteQuestIds.isEmpty;
  bool get hasVerifiedRoute => mapNames.isNotEmpty;
}

