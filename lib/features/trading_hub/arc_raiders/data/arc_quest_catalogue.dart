  static final Map<String, ArcQuestCatalogueNode> byId =
      <String, ArcQuestCatalogueNode>{for (final node in nodes) node.id: node};

  static final Map<String, List<ArcQuestCatalogueNode>> childrenByQuestId =
      _buildChildren();

  static ArcQuestCatalogueNode? findByName(String questName) {
    final wanted = _normalize(questName);
    for (final node in nodes) {
      if (_normalize(node.displayName) == wanted) return node;
    }
    return null;
  }

  static String normalizedKey(String trader, String questName) =>
      '${_normalize(trader)}|${_normalize(questName)}';

  static List<ArcQuestCatalogueNode> childrenOf(String questId) =>
      childrenByQuestId[questId] ?? const <ArcQuestCatalogueNode>[];

  static Map<String, List<ArcQuestCatalogueNode>> _buildChildren() {
    final output = <String, List<ArcQuestCatalogueNode>>{
      for (final node in nodes) node.id: <ArcQuestCatalogueNode>[],
    };
    for (final node in nodes) {
      for (final parent in node.prerequisiteQuestIds) {
        output.putIfAbsent(parent, () => <ArcQuestCatalogueNode>[]).add(node);
      }
    }
    for (final children in output.values) {
      children.sort(
        (left, right) => left.canonicalOrder.compareTo(right.canonicalOrder),
      );
    }
    return output.map(
      (key, value) =>
          MapEntry(key, List<ArcQuestCatalogueNode>.unmodifiable(value)),
    );
  }

  static String _normalize(String value) {
    return value
        .trim()
        .toLowerCase()
        .replaceAll('’', "'")
        .replaceAll(RegExp(r'[^a-z0-9]+'), ' ')
        .replaceAll(RegExp(r'\s+'), ' ')
        .trim();
  }
